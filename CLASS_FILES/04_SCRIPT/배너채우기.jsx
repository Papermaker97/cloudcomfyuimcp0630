function JSON파싱(문자열) {                          // 텍스트를 받아서,
    // 최신 프로그램에는 JSON 기능이 내장돼 있어 그것을 먼저 씁니다.
    if (typeof JSON !== "undefined" && JSON.parse) { return JSON.parse(문자열); } // 있으면 사용.
    // 없으면 예비 방식으로 해석합니다. (안전을 위해 위험 문자를 막습니다)
    return eval("(" + 문자열 + ")");                // 괄호로 감싸 객체로 해석합니다.
}                                                  // 함수 끝.

