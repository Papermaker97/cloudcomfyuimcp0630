// [도우미] 레이어 이름으로 레이어 찾기 (그룹 안까지 뒤져줍니다)
// ------------------------------------------------------------
function 레이어찾기(컨테이너, 이름) {                // 문서나 그룹과 찾을 이름을 받아서,
    for (var i = 0; i < 컨테이너.layers.length; i++) { // 그 안의 레이어를 하나씩 보며,
        var 레이어 = 컨테이너.layers[i];             // 지금 살펴볼 레이어입니다.
        if (레이어.name === 이름) { return 레이어; } // 이름이 같으면 그 레이어를 돌려줍니다.
        // 그룹(레이어셋)이면 그 안쪽도 재귀적으로 찾아봅니다.
        if (레이어.typename === "LayerSet") {        // 이 레이어가 그룹이라면,
            var 찾음 = 레이어찾기(레이어, 이름);     // 그룹 내부를 다시 뒤지고,
            if (찾음) { return 찾음; }               // 찾았으면 돌려줍니다.
        }                                           // 그룹 처리 끝.
    }                                               // 반복 끝.
    return null;                                     // 끝까지 못 찾으면 없음(null)을 돌려줍니다.
}                                                   // 함수 끝.

// ------------------------------------------------------------
// [도우미] 가격 숫자에 천 단위 콤마 넣기 (25000 → 25,000)
// ------------------------------------------------------------
function 콤마넣기(숫자) {                            // 숫자를 받아서,
    var 글자 = String(숫자);                         // 문자열로 바꾼 뒤,
    // 정규식으로 세 자리마다 콤마를 끼워 넣습니다.
    return 글자.replace(/\B(?=(\d{3})+(?!\d))/g, ","); // 콤마가 들어간 문자열을 돌려줍니다.
}                                                   // 함수 끝.

