// ============================================================
// 영상채우기.jsx  (After Effects 용)
// ------------------------------------------------------------
// 하는 일: config.json에 적힌 상품 정보를 읽어서
//          broadcast_template.aep 템플릿의
//            - PRODUCT_IMAGE (푸티지/소스 파일) → 상품 이미지 교체
//            - PRODUCT_NAME  (텍스트 레이어) → 상품명 교체
//            - PRICE         (텍스트 레이어) → 가격 교체
//          를 자동으로 바꾸고, OUTPUT 컴포지션을 렌더큐에 넣습니다.
// 실행 방법: After Effects 메뉴 > 파일 > 스크립트 > 스크립트 파일 실행 > 이 파일 선택
// 원칙: 템플릿(엔진)은 안 바꾸고, config.json(데이터)만 바꿉니다.
// ============================================================

// ------------------------------------------------------------
// [0단계] "스크립트 파일 쓰기/네트워크 허용" 설정이 켜져 있는지 확인
//  (꺼져 있으면 파일 교체가 막히므로, 한국어로 켜는 방법을 안내합니다)
// ------------------------------------------------------------
(function () {                                       // 전체를 하나의 함수로 감싸 변수 충돌을 막습니다.

var 쓰기허용 = true;                                // 기본값은 '허용됨'으로 둡니다.
try {                                               // 환경설정 값을 읽어 봅니다.
    // 이 값이 1이면 허용, 0이면 차단 상태입니다.
    쓰기허용 = (app.preferences.getPrefAsLong("Main Pref Section", "Pref_SCRIPTING_FILE_NETWORK_SECURITY") === 1); // 설정 읽기.
} catch (e) {                                        // 버전에 따라 못 읽을 수도 있는데,
    쓰기허용 = true;                                // 그럴 땐 일단 진행합니다.
}                                                   // 확인 끝.
if (!쓰기허용) {                                     // 만약 차단 상태라면,
    alert("스크립트의 파일 쓰기가 꺼져 있습니다.\n\n[켜는 방법]\n편집(또는 After Effects) > 환경 설정 > 스크립팅 및 표현식\n> '스크립트가 파일에 쓰고 네트워크에 액세스하도록 허용'에 체크한 뒤\n다시 실행하세요."); // 안내.
    return;                                         // 여기서 멈춥니다.
}                                                   // 확인 끝.

// ------------------------------------------------------------
// [1단계] 폴더 경로 계산 (한글/공백 경로에서도 안전)
// ------------------------------------------------------------
var 이스크립트 = new File($.fileName);              // 실행 중인 이 파일 자신입니다.
var 스크립트폴더 = 이스크립트.parent;                // 04_SCRIPT 폴더입니다.
var 루트폴더 = 스크립트폴더.parent;                  // CLASS_FILES 루트 폴더입니다.
var 설정파일 = new File(스크립트폴더.fsName + "/config.json"); // 데이터가 담긴 config.json 입니다.
var 템플릿파일 = new File(루트폴더.fsName + "/03_AFTER_EFFECTS/broadcast_template.aep"); // 영상 템플릿입니다.
var 출력폴더 = new Folder(루트폴더.fsName + "/05_OUTPUT"); // 결과를 저장할 폴더입니다.
if (!출력폴더.exists) { 출력폴더.create(); }          // 출력 폴더가 없으면 만듭니다.

// ------------------------------------------------------------
// [2단계] config.json 읽기 + 문법 검사
// ------------------------------------------------------------
function JSON파싱(문자열) {                           // 텍스트를 데이터로 바꾸는 함수입니다.
    if (typeof JSON !== "undefined" && JSON.parse) { return JSON.parse(문자열); } // 내장 기능이 있으면 사용.
    return eval("(" + 문자열 + ")");                 // 없으면 예비 방식으로 해석합니다.
}                                                   // 함수 끝.

if (!설정파일.exists) {                              // config.json 이 없으면,
    alert("config.json 파일을 찾을 수 없습니다.\n경로: " + 설정파일.fsName + "\n\n04_SCRIPT 폴더 안에 config.json이 있는지 확인하세요."); // 안내.
    return;                                         // 멈춥니다.
}                                                   // 확인 끝.

설정파일.encoding = "UTF-8";                          // 한글이 깨지지 않도록 UTF-8로 읽습니다.
설정파일.open("r");                                   // 읽기 모드로 열고,
var 설정텍스트 = 설정파일.read();                     // 내용을 통째로 읽고,
설정파일.close();                                     // 닫습니다.

var 설정;                                            // 해석 결과를 담을 변수입니다.
try {                                               // 해석을 시도합니다.
    설정 = JSON파싱(설정텍스트);                     // 텍스트 → 데이터.
} catch (e) {                                        // 문법이 틀리면,
    alert("config.json 문법에 오류가 있습니다.\n\n다음을 확인하세요.\n1) 값과 값 사이에 쉼표(,)가 있는지\n2) 맨 마지막 값 뒤에는 쉼표가 없는지\n3) 글자값은 큰따옴표(\")로 감쌌는지\n\n원문 오류: " + e.message); // 4규칙 안내.
    return;                                         // 멈춥니다.
}                                                   // 해석 끝.

// ------------------------------------------------------------
// [3단계] 템플릿 프로젝트 열기
// ------------------------------------------------------------
if (!템플릿파일.exists) {                            // 영상 템플릿이 없으면,
    alert("broadcast_template.aep 를 찾을 수 없습니다.\n경로: " + 템플릿파일.fsName + "\n\n03_AFTER_EFFECTS 폴더를 확인하세요."); // 안내.
    return;                                         // 멈춥니다.
}                                                   // 확인 끝.

app.open(템플릿파일);                                // 영상 템플릿(.aep)을 엽니다.
var 프로젝트 = app.project;                          // 방금 연 프로젝트를 가리킵니다.

// 여러 단계를 하나의 '실행 취소' 단위로 묶습니다. (Ctrl+Z 한 번에 되돌리기 편하게)
app.beginUndoGroup("영상채우기 자동 변경");         // 실행 취소 그룹 시작.

try {                                               // 작업 중 문제가 나도 마무리(그룹 종료)하도록 감쌉니다.

    // --------------------------------------------------------
    // [도우미] 프로젝트에서 이름과 종류로 항목 찾기
    // --------------------------------------------------------
    function 항목찾기(이름, 종류) {                   // 찾을 이름과 종류("footage"/"comp")를 받아,
        for (var i = 1; i <= 프로젝트.numItems; i++) { // 프로젝트의 모든 항목을 하나씩 보며,
            var 항목 = 프로젝트.item(i);              // 지금 살펴볼 항목입니다.
            if (항목.name !== 이름) { continue; }     // 이름이 다르면 건너뜁니다.
            if (종류 === "footage" && (항목 instanceof FootageItem)) { return 항목; } // 푸티지를 찾을 때.
            if (종류 === "comp" && (항목 instanceof CompItem)) { return 항목; } // 컴포지션을 찾을 때.
        }                                            // 반복 끝.
        return null;                                  // 못 찾으면 없음(null)을 돌려줍니다.
    }                                                // 함수 끝.

    // --------------------------------------------------------
    // (a) 상품 이미지 교체: PRODUCT_IMAGE 푸티지의 소스 파일을 바꿉니다.
    // --------------------------------------------------------
    var 상품이미지파일 = new File(루트폴더.fsName + "/" + 설정.productImage); // config 경로를 실제 파일로 만듭니다.
    if (!상품이미지파일.exists) {                     // 상품 이미지가 없으면,
        alert("상품 이미지를 찾을 수 없습니다.\n경로: " + 상품이미지파일.fsName + "\n\nconfig.json의 productImage 값과 01_INPUT 폴더의 파일 이름이 같은지 확인하세요."); // 안내.
        return;                                      // 멈춥니다.
    }                                                // 확인 끝.
    var 이미지푸티지 = 항목찾기("PRODUCT_IMAGE", "footage"); // PRODUCT_IMAGE 푸티지를 찾습니다.
    if (!이미지푸티지) {                              // 못 찾으면,
        alert("PRODUCT_IMAGE 푸티지를 찾을 수 없습니다.\n프로젝트 패널에서 소스 이름이 PRODUCT_IMAGE 인지 확인하세요."); // 안내.
        return;                                      // 멈춥니다.
    }                                                // 확인 끝.
    이미지푸티지.replace(상품이미지파일);             // 푸티지의 소스를 새 상품 이미지로 교체합니다.

    // --------------------------------------------------------
    // (b),(c) 텍스트 교체: MAIN 컴포지션 안의 텍스트 레이어를 바꿉니다.
    // --------------------------------------------------------
    var 메인컴프 = 항목찾기("MAIN", "comp");         // 상품명/가격이 들어있는 MAIN 컴포지션을 찾습니다.
    if (!메인컴프) {                                  // 못 찾으면,
        alert("MAIN 컴포지션을 찾을 수 없습니다.\n컴포지션 이름이 MAIN 인지 확인하세요."); // 안내.
        return;                                      // 멈춥니다.
    }                                                // 확인 끝.

    // 콤마 넣는 도우미 함수입니다. (25000 → 25,000)
    function 콤마넣기(숫자) {                          // 숫자를 받아서,
        return String(숫자).replace(/\B(?=(\d{3})+(?!\d))/g, ","); // 세 자리마다 콤마를 넣어 돌려줍니다.
    }                                                // 함수 끝.

    // 텍스트 레이어 하나의 글자를 안전하게 바꾸는 도우미입니다.
    function 텍스트바꾸기(컴프, 레이어이름, 새글자) {   // 컴포지션/레이어이름/새 글자를 받아,
        var 레이어 = null;                            // 찾은 레이어를 담을 변수입니다.
        try { 레이어 = 컴프.layer(레이어이름); } catch (e) { 레이어 = null; } // 이름으로 레이어를 찾습니다.
        if (!레이어) {                                // 못 찾으면,
            alert(레이어이름 + " 텍스트 레이어를 찾을 수 없습니다.\nMAIN 컴포지션의 레이어 이름을 확인하세요."); // 안내.
            return false;                            // 실패를 알립니다.
        }                                            // 확인 끝.
        var 소스텍스트 = 레이어.property("Source Text"); // 그 레이어의 글자 속성을 가져옵니다.
        var 문서 = 소스텍스트.value;                  // 현재 글자 서식이 담긴 문서를 복사합니다.(서식 유지)
        문서.text = 새글자;                           // 글자 내용만 새 값으로 바꿉니다.
        소스텍스트.setValue(문서);                    // 바뀐 글자를 레이어에 적용합니다.
        return true;                                 // 성공을 알립니다.
    }                                                // 함수 끝.

    // 상품명을 바꿉니다. (실패하면 위 함수가 안내 후 false를 돌려주므로 여기서 멈춥니다)
    if (!텍스트바꾸기(메인컴프, "PRODUCT_NAME", 설정.productName)) { return; } // 상품명 교체.

    // 가격 값이 있으면 "25,000원" 형태로 바꿉니다.
    if (설정.price !== undefined && 설정.price !== null && 설정.price !== "") { // 가격이 있으면,
        if (!텍스트바꾸기(메인컴프, "PRICE", 콤마넣기(설정.price) + "원")) { return; } // 가격 교체.
    }                                                // 가격 처리 끝.

    // --------------------------------------------------------
    // (d) OUTPUT 컴포지션을 렌더큐에 추가하고 저장 경로를 정합니다.
    // --------------------------------------------------------
    var 출력컴프 = 항목찾기("OUTPUT", "comp");        // 최종 출력용 OUTPUT 컴포지션을 찾습니다.
    if (!출력컴프) {                                  // 못 찾으면,
        alert("OUTPUT 컴포지션을 찾을 수 없습니다.\n최종 출력용 컴포지션 이름이 OUTPUT 인지 확인하세요."); // 안내.
        return;                                      // 멈춥니다.
    }                                                // 확인 끝.
    var 렌더항목 = 프로젝트.renderQueue.items.add(출력컴프); // OUTPUT을 렌더큐에 추가합니다.
    var 출력모듈 = 렌더항목.outputModule(1);          // 그 렌더 항목의 출력 설정을 가져옵니다.
    // 저장 파일명에 상품명을 넣어 구분합니다.(금지문자는 밑줄로 치환)
    var 안전한상품명 = String(설정.productName).replace(/[\\\/:*?"<>|]/g, "_"); // 금지문자 치환.
    // 확장자는 붙이지 않습니다. 렌더 설정(출력 모듈)이 형식에 맞게 자동으로 붙입니다.
    출력모듈.file = new File(출력폴더.fsName + "/방송_" + 안전한상품명); // 저장 경로를 지정합니다.

    // --------------------------------------------------------
    // 마무리 안내. (여기서는 렌더큐에 넣기만 하고, 실제 렌더는 사용자가 시작)
    // --------------------------------------------------------
    alert("영상 템플릿 채우기 완료!\n\n상품: " + 설정.productName + "\n\n[다음 단계]\n하단 '렌더링 대기열'에서 초록색 '렌더링' 버튼을 누르면\n05_OUTPUT 폴더에 영상이 저장됩니다."); // 완료 안내.

} catch (오류) {                                     // 예상 못 한 문제가 생기면,
    alert("영상 채우기 중 문제가 발생했습니다.\n\n" + 오류.toString()); // 오류 내용을 안내합니다.
} finally {                                          // 성공/실패와 상관없이,
    app.endUndoGroup();                              // 실행 취소 그룹을 닫습니다.
}                                                   // try/finally 끝.

})();                                                // 감싼 함수를 즉시 실행합니다.
