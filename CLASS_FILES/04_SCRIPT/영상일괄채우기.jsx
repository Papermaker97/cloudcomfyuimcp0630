// ============================================================
// 영상일괄채우기.jsx  (After Effects 용)
// ------------------------------------------------------------
// 하는 일: 04_SCRIPT/배치_설정/ 폴더 안에 있는 config 파일을
//          "여러 개" 순서대로 읽어서, 상품마다
//            - PRODUCT_IMAGE (푸티지) → 상품 이미지 교체
//            - PRODUCT_NAME  (텍스트) → 상품명 교체
//            - PRICE         (텍스트) → 가격 교체
//          를 바꾼 뒤, 그 상태 그대로 "바로 렌더"까지 끝내고
//          다음 상품으로 넘어갑니다. (한 번의 실행으로 영상 여러 개 완성)
// 실행 방법: After Effects 메뉴 > 파일 > 스크립트 > 스크립트 파일 실행 > 이 파일 선택
// 영상채우기.jsx와 다른 점: 영상채우기.jsx는 config.json 1개 → 영상 1개(렌더큐 등록까지만).
//                          이 스크립트는 config 여러 개 → 영상 여러 개(렌더 완료까지).
// ⚠️ 상품 수만큼 렌더 시간이 걸립니다. 다 끝날 때까지 기다려야 합니다.
// ============================================================

(function () {                                       // 전체를 하나의 함수로 감싸 변수 충돌을 막습니다.

// ------------------------------------------------------------
// [0단계] "스크립트 파일 쓰기/네트워크 허용" 설정이 켜져 있는지 확인
// ------------------------------------------------------------
var 쓰기허용 = true;                                // 기본값은 '허용됨'으로 둡니다.
try {                                               // 환경설정 값을 읽어 봅니다.
    쓰기허용 = (app.preferences.getPrefAsLong("Main Pref Section", "Pref_SCRIPTING_FILE_NETWORK_SECURITY") === 1); // 설정 읽기.
} catch (e) {                                        // 버전에 따라 못 읽을 수도 있는데,
    쓰기허용 = true;                                // 그럴 땐 일단 진행합니다.
}                                                   // 확인 끝.
if (!쓰기허용) {                                     // 만약 차단 상태라면,
    alert("스크립트의 파일 쓰기가 꺼져 있습니다.\n\n[켜는 방법]\n편집(또는 After Effects) > 환경 설정 > 스크립팅 및 표현식\n> '스크립트가 파일에 쓰고 네트워크에 액세스하도록 허용'에 체크한 뒤\n다시 실행하세요."); // 안내.
    return;                                         // 여기서 멈춥니다.
}                                                   // 확인 끝.

// ------------------------------------------------------------
// [1단계] 폴더 경로 계산 (한글/공백 경로에서도 안전)
// ------------------------------------------------------------
var 이스크립트 = new File($.fileName);              // 실행 중인 이 파일 자신입니다.
var 스크립트폴더 = 이스크립트.parent;                // 04_SCRIPT 폴더입니다.
var 루트폴더 = 스크립트폴더.parent;                  // CLASS_FILES 루트 폴더입니다.
var 배치폴더 = new Folder(스크립트폴더.fsName + "/배치_설정"); // 여러 config 파일이 들어있는 폴더입니다.
var 템플릿파일 = new File(루트폴더.fsName + "/03_AFTER_EFFECTS/broadcast_template.aep"); // 영상 템플릿입니다.
var 출력폴더 = new Folder(루트폴더.fsName + "/05_OUTPUT"); // 결과를 저장할 폴더입니다.
if (!출력폴더.exists) { 출력폴더.create(); }          // 출력 폴더가 없으면 만듭니다.

// ------------------------------------------------------------
// [2단계] 배치_설정 폴더에서 config 파일들을 전부 찾습니다.
// ------------------------------------------------------------
if (!배치폴더.exists) {                              // 배치_설정 폴더가 없으면,
    alert("배치_설정 폴더를 찾을 수 없습니다.\n경로: " + 배치폴더.fsName + "\n\n04_SCRIPT 폴더 안에 배치_설정 폴더를 만들고,\n그 안에 product_01.json 같은 config 파일들을 넣어주세요."); // 안내.
    return;                                         // 멈춥니다.
}                                                   // 확인 끝.

var 설정파일목록 = 배치폴더.getFiles("*.json");     // 폴더 안의 모든 json 파일을 가져옵니다.
if (!설정파일목록 || 설정파일목록.length === 0) {    // 파일이 하나도 없으면,
    alert("배치_설정 폴더 안에 json 파일이 없습니다.\n경로: " + 배치폴더.fsName + "\n\nproduct_01.json 처럼 config 파일을 넣어주세요."); // 안내.
    return;                                         // 멈춥니다.
}                                                   // 확인 끝.
// 파일 이름 순서대로(가나다/숫자 순) 처리되도록 정렬합니다.
설정파일목록.sort(function (a, b) { return a.name < b.name ? -1 : (a.name > b.name ? 1 : 0); }); // 이름순 정렬.

// ------------------------------------------------------------
// [도우미] JSON 문자열을 데이터로 바꾸기 (구버전 대비 예비 처리 포함)
// ------------------------------------------------------------
function JSON파싱(문자열) {                           // 텍스트를 받아서,
    if (typeof JSON !== "undefined" && JSON.parse) { return JSON.parse(문자열); } // 내장 기능이 있으면 사용.
    return eval("(" + 문자열 + ")");                 // 없으면 예비 방식으로 해석합니다.
}                                                   // 함수 끝.

// ------------------------------------------------------------
// [도우미] 프로젝트에서 이름과 종류로 항목 찾기
// ------------------------------------------------------------
function 항목찾기(프로젝트, 이름, 종류) {              // 찾을 이름과 종류("footage"/"comp")를 받아,
    for (var i = 1; i <= 프로젝트.numItems; i++) {   // 프로젝트의 모든 항목을 하나씩 보며,
        var 항목 = 프로젝트.item(i);                  // 지금 살펴볼 항목입니다.
        if (항목.name !== 이름) { continue; }         // 이름이 다르면 건너뜁니다.
        if (종류 === "footage" && (항목 instanceof FootageItem)) { return 항목; } // 푸티지를 찾을 때.
        if (종류 === "comp" && (항목 instanceof CompItem)) { return 항목; } // 컴포지션을 찾을 때.
    }                                                // 반복 끝.
    return null;                                      // 못 찾으면 없음(null)을 돌려줍니다.
}                                                   // 함수 끝.

// ------------------------------------------------------------
// [도우미] 콤마 넣기 (25000 → 25,000)
// ------------------------------------------------------------
function 콤마넣기(숫자) {                             // 숫자를 받아서,
    return String(숫자).replace(/\B(?=(\d{3})+(?!\d))/g, ","); // 세 자리마다 콤마를 넣어 돌려줍니다.
}                                                   // 함수 끝.

// ------------------------------------------------------------
// [도우미] 텍스트 레이어 글자 바꾸기
// ------------------------------------------------------------
function 텍스트바꾸기(컴프, 레이어이름, 새글자) {       // 컴포지션/레이어이름/새 글자를 받아,
    var 레이어 = null;                                // 찾은 레이어를 담을 변수입니다.
    try { 레이어 = 컴프.layer(레이어이름); } catch (e) { 레이어 = null; } // 이름으로 레이어를 찾습니다.
    if (!레이어) { return false; }                    // 못 찾으면 실패를 알립니다.
    var 소스텍스트 = 레이어.property("Source Text");   // 그 레이어의 글자 속성을 가져옵니다.
    var 문서객체 = 소스텍스트.value;                   // 현재 글자 서식이 담긴 문서를 복사합니다.(서식 유지)
    문서객체.text = 새글자;                            // 글자 내용만 새 값으로 바꿉니다.
    소스텍스트.setValue(문서객체);                     // 바뀐 글자를 레이어에 적용합니다.
    return true;                                      // 성공을 알립니다.
}                                                   // 함수 끝.

// ------------------------------------------------------------
// [3단계] 영상 템플릿을 "한 번만" 엽니다. (상품마다 다시 열지 않고 재사용합니다)
// ------------------------------------------------------------
if (!템플릿파일.exists) {                            // 영상 템플릿이 없으면,
    alert("broadcast_template.aep 를 찾을 수 없습니다.\n경로: " + 템플릿파일.fsName); // 안내.
    return;                                         // 멈춥니다.
}                                                   // 확인 끝.

app.open(템플릿파일);                                // 영상 템플릿(.aep)을 엽니다.
var 프로젝트 = app.project;                          // 방금 연 프로젝트를 가리킵니다.

var 메인컴프 = 항목찾기(프로젝트, "MAIN", "comp");   // 상품명/가격이 들어있는 MAIN 컴포지션.
var 출력컴프 = 항목찾기(프로젝트, "OUTPUT", "comp"); // 최종 출력용 OUTPUT 컴포지션.
var 이미지푸티지 = 항목찾기(프로젝트, "PRODUCT_IMAGE", "footage"); // 상품 이미지 푸티지.

if (!메인컴프 || !출력컴프 || !이미지푸티지) {         // 셋 중 하나라도 없으면,
    alert("템플릿 구조를 확인할 수 없습니다.\nMAIN / OUTPUT 컴포지션, PRODUCT_IMAGE 푸티지 이름을 확인하세요."); // 안내.
    return;                                         // 멈춥니다.
}                                                   // 확인 끝.

// ------------------------------------------------------------
// [4단계] config 파일 하나씩 돌면서: 데이터 채우기 → 렌더큐 등록 → 바로 렌더
//         (다음 상품으로 넘어가기 전에 반드시 "이번 상품 렌더를 끝냅니다"
//          — 그래야 여러 영상이 전부 다른 내용으로 나옵니다)
// ------------------------------------------------------------
var 성공목록 = [];                                   // 성공한 상품명을 모아둘 목록입니다.
var 실패목록 = [];                                   // 실패한 파일명 + 이유를 모아둘 목록입니다.

for (var i = 0; i < 설정파일목록.length; i++) {       // config 파일을 하나씩 순서대로 돌면서,
    var 설정파일 = 설정파일목록[i];                    // 지금 처리할 config 파일입니다.
    try {                                             // 이 상품 처리 중 문제가 나도 다음 상품으로 넘어가도록 감쌉니다.

        // (a) config 읽고 해석하기
        설정파일.encoding = "UTF-8";                  // 한글이 깨지지 않도록 UTF-8로 읽습니다.
        설정파일.open("r");                           // 읽기 모드로 열고,
        var 설정텍스트 = 설정파일.read();              // 내용을 통째로 읽고,
        설정파일.close();                              // 닫습니다.
        var 설정 = JSON파싱(설정텍스트);               // 텍스트 → 데이터로 변환. (문법 오류면 아래 catch로 갑니다)

        if (!설정.productName || !설정.productImage) { // 필수 값이 없으면,
            throw new Error("productName 또는 productImage 값이 비어 있습니다.");
        }                                             // 확인 끝.

        // (b) 상품 이미지 교체
        var 상품이미지파일 = new File(루트폴더.fsName + "/" + 설정.productImage); // 실제 이미지 경로.
        if (!상품이미지파일.exists) {                  // 이미지가 없으면,
            throw new Error("상품 이미지를 찾을 수 없습니다: " + 상품이미지파일.fsName);
        }                                             // 확인 끝.
        이미지푸티지.replace(상품이미지파일);          // 푸티지 소스를 새 이미지로 교체합니다.

        // (c) 상품명 / 가격 텍스트 교체
        if (!텍스트바꾸기(메인컴프, "PRODUCT_NAME", 설정.productName)) { // 상품명 교체 실패 시,
            throw new Error("PRODUCT_NAME 텍스트 레이어를 찾을 수 없습니다.");
        }                                             // 확인 끝.
        if (설정.price !== undefined && 설정.price !== null && 설정.price !== "") { // 가격 값이 있으면,
            if (!텍스트바꾸기(메인컴프, "PRICE", 콤마넣기(설정.price) + "원")) { // 가격 교체 실패 시,
                throw new Error("PRICE 텍스트 레이어를 찾을 수 없습니다.");
            }                                         // 확인 끝.
        }                                             // 가격 처리 끝.

        // (d) 이번 상품의 결과를 렌더큐에 등록하고, 파일명을 지정합니다.
        var 안전한상품명 = String(설정.productName).replace(/[\\\/:*?"<>|]/g, "_"); // 금지문자 치환.
        var 렌더항목 = 프로젝트.renderQueue.items.add(출력컴프); // OUTPUT을 렌더큐에 새로 추가합니다.
        var 출력모듈 = 렌더항목.outputModule(1);       // 그 렌더 항목의 출력 설정을 가져옵니다.
        출력모듈.file = new File(출력폴더.fsName + "/방송_" + 안전한상품명); // 저장 경로 지정. (확장자는 자동)

        // (e) ★ 여기서 바로 렌더를 실행하고 끝날 때까지 기다립니다.
        //     (다음 상품 데이터로 넘어가기 전에 반드시 지금 상품을 렌더 완료해야
        //      영상마다 서로 다른 내용이 담깁니다. 안 그러면 전부 마지막 상품으로 나옵니다)
        프로젝트.renderQueue.render();                 // 지금 대기 중인 렌더 항목을 전부 처리(=이번 항목)합니다.

        성공목록.push(설정.productName + " (" + 설정파일.name + ")"); // 성공 기록.

    } catch (오류) {                                   // 이 상품 처리 중 문제가 생기면,
        실패목록.push(설정파일.name + " → " + 오류.message); // 실패 내용을 기록하고,
        // continue 없이 자연스럽게 다음 반복(다음 상품)으로 넘어갑니다.
    }                                                  // try/catch 끝.
}                                                    // 전체 config 파일 반복 끝.

// ------------------------------------------------------------
// [5단계] 마무리 안내 (전체 결과 요약)
// ------------------------------------------------------------
app.project.close(CloseOptions.DO_NOT_SAVE_CHANGES);  // 템플릿은 저장하지 않고 닫습니다. (원본 보호)

var 결과메시지 = "일괄 렌더 완료!\n\n"                // 제목 줄.
    + "총 " + 설정파일목록.length + "개 상품 중 "
    + 성공목록.length + "개 성공, " + 실패목록.length + "개 실패.\n\n";
if (성공목록.length > 0) {                            // 성공한 게 있으면,
    결과메시지 += "[성공]\n" + 성공목록.join("\n") + "\n\n"; // 목록 추가.
}                                                    // 조건 끝.
if (실패목록.length > 0) {                            // 실패한 게 있으면,
    결과메시지 += "[실패]\n" + 실패목록.join("\n");     // 목록 추가.
}                                                    // 조건 끝.
결과메시지 += "\n\n저장 위치: 05_OUTPUT";              // 저장 위치 안내.
alert(결과메시지);                                    // 최종 결과를 알림창으로 보여줍니다.

})();                                                 // 감싼 함수를 즉시 실행합니다.
